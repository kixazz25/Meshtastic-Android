/*
 * STEP15E-2026-11-09: TEST-ONLY copy of the app's (2.7e) GPX import -- ConvoyTrackOps.importGpxAllArtifacts and the per-file loop of
 * ConvoyTrackImportScreen.doImport -- the OLD side of the step 15e certification (GtCert15e). GENERATED by make_old_copies_15e.py; do not
 * edit by hand. Changes, and only these: tracksDir() -> certTracksDir(); SpatialDbManager.resolveTrackAdd / insertWaypoint ->
 * TrackSyncCertOld's (15d's generated copy); DownloadQueueManager.enqueueCorridor -> certEnqueueCorridor (recorded);
 * RiderTrailWriter.trailsChanged -> certTrailsChanged (counted); ImportConverter.saveToDownloads -> certSaveToDownloads (recorded);
 * context.cacheDir -> certCache(); Date() -> certDate() (the fixed batch date). The folders are the cert copy's -- set by GtCert15e before
 * a run and cleared after; unset -> IllegalStateException (never the live folders).
 * ⚠ TEST-ONLY (CODE RULE 3): remove with GtCertRun before 2.8 is released.
 */
object GpxImportCertOld {
    /** the cert copy's cache folder (GtCert15e; my_tracks is TrackSyncCertOld.certTracks). CODE RULE 1: null = not in a cert run. */
    @Volatile var certCacheDir: File? = null
    /** what the copy asked the platform to do (enqueueCorridor, saveToDownloads), in order -- compared, never done */
    val certCalls = java.util.Collections.synchronizedList(ArrayList<String>())
    @Volatile var trailsChangedCount = 0
    /** the tiles certEnqueueCorridor "queues" (any fixed number: the MAPS lines print it) -- the NEW side's cert env returns the same */
    const val CERT_TILES = 7

    private fun certTracksDir(): File {
        val dir = TrackSyncCertOld.certTracks ?: throw IllegalStateException("GpxImportCertOld: no cert my_tracks set")
        if (!dir.exists()) dir.mkdirs()   // as ConvoyTrackOps.tracksDir()
        return dir
    }
    private fun certCache(): File = certCacheDir ?: throw IllegalStateException("GpxImportCertOld: no cert cache folder set")
    @Suppress("UNUSED_PARAMETER")
    private fun certEnqueueCorridor(context: android.content.Context, geomHash: String, slot: String, replaceExisting: Boolean): Int {
        certCalls.add("enqueueCorridor|$geomHash|$slot|$replaceExisting"); return CERT_TILES
    }
    private fun certSaveToDownloads(f: File): String { certCalls.add("saveToDownloads|" + f.name); return "cert-" + f.name }
    private fun certTrailsChanged() { trailsChangedCount++ }
    /** 2026-11-01 12:00:00 in the device's zone (SimpleDateFormat formats it in that zone: "2026-11-01") */
    private fun certDate(): java.util.Date = java.util.Calendar.getInstance().apply { clear(); set(2026, java.util.Calendar.NOVEMBER, 1, 12, 0, 0) }.time

    // ---- the screen's state the copied loop assigns (setters hand the news to the caller) ----
    private var onLineSink: ((String) -> Unit)? = null   // CODE RULE 1: null = no run in progress
    private var onFileSink: ((Int, String) -> Unit)? = null   // CODE RULE 1: null = no run in progress
    private var importLines: List<String> = emptyList()
        set(v) { val s = onLineSink; if (s != null) for (k in field.size until v.size) s(v[k]); field = v }
    private var progressCurrent = 0
    private var progressName = ""
        set(v) { field = v; onFileSink?.invoke(progressCurrent, v) }

    /** ConvoyTrackImportScreen.doImport's loop, as the screen runs it (the copied body below), returning the totals it adds up. */
    suspend fun importFiles(context: android.content.Context, sel: List<File>, trailsAnswer: String, trailsSource: String, mapsSkip: Set<String>,
                            selectedSlots: List<String>, replaceExisting: Boolean, onLine: (String) -> Unit, onFile: (Int, String) -> Unit): GtGpxImport.Totals {
        onLineSink = null; onFileSink = null; importLines = emptyList(); progressCurrent = 0
        onLineSink = onLine; onFileSink = onFile
        try {
// ---- loop (verbatim from ConvoyTrackImportScreen.kt) ----
            val imported = mutableListOf<String>()
            val skipped = mutableListOf<String>()
            val failed = mutableListOf<String>()
            var datesCorrected = 0
            var wptTotal = 0
            var rteTotal = 0
            var newTotal = 0
            var dupeTotal = 0
            var aliasedTotal = 0
            var skippedTotal = 0
            for ((i, f) in sel.withIndex()) {
                progressCurrent = i + 1
                progressName = f.name
                importLines = importLines + "— ${f.name} —"
                try {
                    // MAPSDEFAULT-2026-09-16: maps unless this file was explicitly excluded.
                    // ONEIMPORT-2026-11-04: YES = every file through the converter (GPX too) -> <name>-Trails.gpx with the trail mark;
                    // NO = KML / KMZ / GeoJSON converted (lines = tracks), GPX as it is. A converted file is also saved to Download.
                    val yes = trailsAnswer == "YES"
                    val ext = ConvoyTrackOps.importExt(f)
                    val conv = if (yes || ext in setOf("kml", "kmz", "geojson", "json")) withContext(Dispatchers.IO) {
                        val od = java.io.File(certCache(), "import_convert").apply { mkdirs() }
                        val r = ImportConverter.toGpx(f, od, yes)
                        val kept = try { "Download/" + certSaveToDownloads(r.file) } catch (e: Exception) { "not saved: ${e.message}" }
                        Pair(r, kept)
                    } else null
                    conv?.let { (r, kept) -> importLines = importLines + "CONVERTED ${f.name}: ${r.lines} ${if (yes) "trails" else "tracks"}, ${r.points} waypoints -> $kept" }
                    val src = conv?.first?.file ?: f
                    // TRAILCLEAN-2026-11-04: the batch every trail of this file is recorded under (YES: the name given; NO: the file name --
                    // a GroupTrack trail export answered NO still brings trails)
                    val batch = (if (yes) trailsSource.trim().ifEmpty { f.nameWithoutExtension } else f.nameWithoutExtension) + " \u00b7 " +
                        java.text.SimpleDateFormat("yyyy-MM-dd", java.util.Locale.US).format(certDate())
                    val summary = importGpxAllArtifacts(src, context, if (!yes && !mapsSkip.contains(f.name)) selectedSlots else emptyList(), replaceExisting, false, batch) { line ->
                        importLines = importLines + line
                    }
                    imported.addAll(summary.trackFiles)
                    wptTotal += summary.waypointCount
                    rteTotal += summary.routeCount
                    datesCorrected += summary.trackFiles.size
                    newTotal += summary.inserted
                    dupeTotal += summary.dropped
                    aliasedTotal += summary.aliased
                    skippedTotal += summary.skipped
                    if (summary.errors.isNotEmpty()) {
                        failed.addAll(summary.errors.map { f.name + ": " + it })
                    }
                } catch (e: Exception) {
                    failed.add(f.name + ": " + (e.message ?: "unknown error"))
                    importLines = importLines + "ERROR: ${f.name}: ${e.message ?: "unknown"}"
                }
            }
            return GtGpxImport.Totals(imported, skipped, failed, datesCorrected, wptTotal, rteTotal, newTotal, dupeTotal, aliasedTotal, skippedTotal)
        } finally { onLineSink = null; onFileSink = null }
    }

    // ---- importGpxAllArtifacts (verbatim from ConvoyTrackOps.kt) ----
    // ── Full Artifact Import ───────────────────────────────────────

    /**
     * Import all artifact types from a GPX file:
     *   - Tracks: create GPX files in my_tracks/ + insert into spatial DB
     *   - Waypoints: insert into spatial DB waypoints table
     *   - Routes: insert into spatial DB tracks table (type='ROUTE')
     *
     * Source file is deleted from Downloads after successful import.
     *
     * @param sourceFile GPX file to import (typically from Downloads)
     * @param context Android context for SpatialDbManager init
     * @return ImportArtifactsSummary with counts per type
     */
    suspend fun importGpxAllArtifacts(
        sourceFile: File,
        context: android.content.Context,
        downloadMapSlots: List<String> = emptyList(),
        replaceExisting: Boolean = false,
        asTrails: Boolean,   // IMPORTTRAILS-2026-10-30: true = every <trk> line goes into trails, not tracks (CODE RULE 1: required)
        trailBatch: String,   // TRAILCLEAN-2026-11-04: "<source name> · <date>" written to every trail's agency_id (CODE RULE 1: required)
        onProgress: ((String) -> Unit)? = null
    ): ImportArtifactsSummary = kotlinx.coroutines.withContext(kotlinx.coroutines.Dispatchers.IO) {
        val sourceName = sourceFile.name
        val errors = mutableListOf<String>()
        val trackFiles = mutableListOf<String>()
        var waypointCount = 0
        var routeCount = 0
        fun diag(msg: String) { android.util.Log.i("ImportDiag", msg); onProgress?.invoke(msg) }
        diag("ENTRY name='$sourceName' exists=${sourceFile.exists()} len=${sourceFile.length()} ext='${sourceFile.extension}'")

        try {
            if (!sourceFile.exists()) {
                return@withContext ImportArtifactsSummary(sourceName, 0, 0, 0, emptyList(), listOf("File not found"))
            }

            // Validate extension before reading (streaming — we never load the whole file)
            if (importExt(sourceFile) != "gpx") {   // GPXDUPNAME-2026-11-01: "x.gpx (2)" is a GPX
                return@withContext ImportArtifactsSummary(sourceName, 0, 0, 0, emptyList(), listOf("Not a GPX file"))
            }

            // Initialize spatial DB
            SpatialDbManager.init(context)
            val dir = certTracksDir()
            if (!dir.exists()) dir.mkdirs()

            // ── 1. Process Tracks (<trk> elements) — STREAMED 2026-06-02 ──
            // Tier-2 streaming: read the file with a BufferedReader and accumulate ONE
            // <trk>..</trk> block at a time, process it, release it. The whole file is
            // never held in memory (was: readText + whole-file regex + findAll().toList(),
            // which OOM'd on large onX exports). Per-track parse/insert logic is reused.
            val namePattern = Regex("""<name>([^<]*)</name>""")
            val extPattern = Regex("""<extensions>[\s\S]*?</extensions>""")
            var trackIndex = 0
            var insertedCount = 0
            var aliasedCount = 0
            var duplicateCount = 0
            var skippedCount = 0

            // PROVEN regex track-detection (mirrors importTrackFile): match <trk>..</trk>
            // across newlines with findAll. Replaces the line-streamer that found 0 tracks.
            // GPXIMPORT-2026-08-22N3: hoisted OUT of the run block. It was scoped inside,
            // so the waypoint and route parsers below could not see it. Reading the
            // file a SECOND time down there would compile, but the comment above
            // records that the whole-file approach OOM'd on large onX exports --
            // two reads doubles that. One read, both consumers.
            val fullText = sourceFile.readText()
            var trailsAdded = 0   // ONEIMPORT-2026-11-04: maps reload when a marked trail went in
            run {
                val trkPattern = Regex("""<trk>([\s\S]*?)</trk>""")
                val matchCount = trkPattern.findAll(fullText).count()
                diag("READ len=${fullText.length} contains<trk>=${fullText.contains("<trk>")} regexMatches=$matchCount")
                for (m in trkPattern.findAll(fullText)) {
                        val rawTrk = m.groupValues[1]
                        val trkContent = extPattern.replace(rawTrk, "")
                        trackIndex++
                        diag("TRACK #$trackIndex trkContentLen=${trkContent.length}")
                        try {
                            val rawName = namePattern.find(trkContent)?.groupValues?.get(1)?.trim()
                                ?: "track_$trackIndex"
                            val baseName = rawName
                                .replace("/", "_").replace("\\", "_")
                                .replace(Regex("[^a-zA-Z0-9_\\- ]"), "")
                                .trim().ifEmpty { "track_$trackIndex" }
                            // IMPORT base fix (2026-06-29): DB-first, hash-named, like save/sync.
                            // Parse geometry FIRST so we can compute the hash that names the file.
                            val coords = SpatialDbManager.parseGpxTrackPoints("<trk>${trkContent}</trk>")
                            if (coords.isEmpty()) {
                                android.util.Log.w("Import", "skip no-geometry trk #$trackIndex ('$baseName')")
                                continue
                            }
                            var minLat = Double.MAX_VALUE; var maxLat = -Double.MAX_VALUE
                            var minLon = Double.MAX_VALUE; var maxLon = -Double.MAX_VALUE
                            for (pair in coords) {
                                val lon = pair.first; val lat = pair.second
                                if (lat < minLat) minLat = lat; if (lat > maxLat) maxLat = lat
                                if (lon < minLon) minLon = lon; if (lon > maxLon) maxLon = lon
                            }
                            val wkt = "LINESTRING(" + coords.joinToString(",") { "${it.first} ${it.second}" } + ")"
                            // IMPORTTRAILS-2026-10-30 (D31-min, Fred 10-30): the rider ticked "Import tracks as trails" -- this
                            // batch is a trail map. Each line becomes a TRAIL; nothing below (track file, track row, corridor) runs.
                            if (asTrails || trailMarked(trkContent, fullText)) {   // ONEIMPORT-2026-11-04: the mark in the file
                                val trailName = namePattern.find(trkContent)?.groupValues?.get(1)?.trim()?.ifEmpty { null }
                                val now = java.time.Instant.now().toString()
                                val res = SpatialDbManager.insertTrail(java.util.UUID.randomUUID().toString(), trailName, wkt,
                                    minLat, maxLat, minLon, maxLon, now)
                                when (res.second) {
                                    SpatialDbManager.AddDecision.INSERT -> {
                                        insertedCount++; trailsAdded++   // ONEIMPORT-2026-11-04
                                        try {
                                            SpatialDbManager.getSpatialDb()?.execSQL(
                                                "UPDATE trails SET carto_code=?, carto_code_source=?, use_type=?, land_status=? WHERE trail_id=?",
                                                arrayOf<Any?>("OHV", "import", TrailClassifier.useOf("OHV"), "PUBLIC", res.first))
                                        } catch (e: Exception) { android.util.Log.w("Import", "trail carto write: ${e.message}") }
                                        try {
                                            SpatialDbManager.getExtensionDb()?.execSQL(
                                                "INSERT OR IGNORE INTO trail_properties " +
                                                    "(trail_id,source_id,source_unique_id,carto_code,motorized_allowed,agency_id,ingested_at) VALUES (?,?,?,?,?,?,?)",   // TRAILCLEAN-2026-11-04: + the batch
                                                arrayOf<Any?>(res.first, "import", SpatialDbManager.computeGeomHash(wkt), "OHV", "yes", trailBatch, now))
                                        } catch (e: Exception) { android.util.Log.w("Import", "trail_properties write: ${e.message}") }
                                        onProgress?.invoke("TRAIL: ${trailName ?: "(no name)"}")
                                    }
                                    SpatialDbManager.AddDecision.ALIAS -> {
                                        aliasedCount++; onProgress?.invoke("TRAIL ALIAS: ${trailName ?: "(no name)"}")
                                    }
                                    SpatialDbManager.AddDecision.DROP -> {
                                        duplicateCount++; onProgress?.invoke("TRAIL DUPLICATE: ${trailName ?: "(no name)"}")
                                    }
                                }
                                continue
                            }
                            // FULLY UNIFORM: write the split track under its HUMAN name (the
                            // same value used for the spatial name). NO hash is computed here --
                            // the resolver owns computeGeomHash, the rename to <hash>.gpx, dedup
                            // (INSERT/DROP/ALIAS), source-file delete, aliasing, and the metric feed.
                            val srcName = "$baseName.gpx"
                            val dest = File(dir, srcName)
                            run {
                                val singleGpx = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n" +
                                    "<gpx version=\"1.1\" creator=\"GroupTrack\">\n" +
                                    "<trk>${trkContent}</trk>\n</gpx>"
                                dest.writeText(singleGpx)
                                extractEarliestTime(singleGpx)?.let { dest.setLastModified(it) }
                                    ?: dest.setLastModified(sourceFile.lastModified())
                            }
                            when (TrackSyncCertOld.resolveTrackAdd(baseName, dest)) {
                                SpatialDbManager.AddOutcome.INSERT -> {
                                    insertedCount++; trackFiles.add(srcName)
                                    onProgress?.invoke("INSERT: $baseName")
                                    // [2026-07-01 maps-follow-tracks] queue this new track's map tiles
                                    // (padded bbox -> download queue). INSERT only; already on IO thread.
                                    // OPT-IN: only when the import-maps checkbox was checked.
                                    if (downloadMapSlots.isNotEmpty()) {
                                        try {
                                            val gh = SpatialDbManager.computeGeomHash(wkt)
                                            // CORRIDOR-CUTOVER-2026-07-24: CORRIDOR, not bbox. The old
                                            // call was ONE submitDownload covering ALL slots;
                                            // corridor is ONE ENTRY PER SOURCE, so this LOOPS.
                                            // getTrackBbox is gone from here - the corridor
                                            // derives from the geometry, and the bounding box
                                            // was only ever the thing being replaced.
                                            // ⚠ 10 tracks x 3 sources = 30 rows, not 10.
                                            var queued = 0
                                            for (slot in downloadMapSlots) {
                                                queued += certEnqueueCorridor(
                                                    context, gh, slot, replaceExisting
                                                )
                                            }
                                            if (queued > 0) {
                                                onProgress?.invoke(
                                                    "MAPS: $baseName corridor queued " +
                                                    "(${downloadMapSlots.size} sources, $queued tiles)")
                                            } else {
                                                onProgress?.invoke("MAPS: $baseName no corridor")
                                            }
                                        } catch (e: Exception) {
                                            onProgress?.invoke("MAPS ERR: $baseName ${e.message}")
                                        }
                                    }
                                }
                                SpatialDbManager.AddOutcome.ALIAS -> {
                                    aliasedCount++
                                    onProgress?.invoke("ALIAS: $baseName")
                                }
                                SpatialDbManager.AddOutcome.DROP_NAME,
                                SpatialDbManager.AddOutcome.DROP_ALIAS -> {
                                    duplicateCount++
                                    onProgress?.invoke("DUPLICATE: $baseName")
                                }
                                SpatialDbManager.AddOutcome.NO_GEOMETRY -> {
                                    skippedCount++
                                    onProgress?.invoke("SKIP: $baseName (no geometry)")
                                }
                                SpatialDbManager.AddOutcome.ERROR -> {
                                    skippedCount++; errors.add("Track $trackIndex: resolveTrackAdd error")
                                    onProgress?.invoke("ERROR: $baseName")
                                }
                            }
                        } catch (e: Exception) {
                            errors.add("Track $trackIndex: ${e.message}")
                        }
                }
            }

            // ── 2. Process Waypoints (<wpt> elements) ──
            // GPXIMPORT-2026-08-22N: BYPASS LIFTED. The 2026-06-02 hold said "re-enable when
            // import logic is built + tested" -- the logic below was already complete
            // the whole time; only this call was stubbed. Testers could not import
            // routes because of it.
            // ⚠ The source file is deleted once anything imports (see step 4). Before
            // this, a waypoints-only GPX imported nothing and survived.
            val waypoints = parseGpxWaypoints(fullText)
            for (wpt in waypoints) {
                try {
                    TrackSyncCertOld.insertWaypoint(wpt.name, wpt.lat, wpt.lon, wpt.type)
                    waypointCount++
                } catch (e: Exception) {
                    errors.add("Waypoint ${wpt.name}: ${e.message}")
                }
            }

            // ── 3. Process Routes (<rte> elements) ──
            // GPXIMPORT-2026-08-22N: BYPASS LIFTED. Coordinate order verified end to end
            // before enabling: the parser stores Pair(lon, lat), the data class
            // documents it, the loop below destructures (lon, lat), and the WKT emits
            // lon lat. No transposition.
            // ⛔ insertRoute writes a PERMANENT spatial-DB row -- an imported route
            // skips draft-then-graduate and is permanent immediately. Permanent routes
            // are the only unrecoverable class on this project.
            val routes = parseGpxRoutes(fullText)
            for (route in routes) {
                try {
                    val pts = route.points
                    var minLat = Double.MAX_VALUE; var maxLat = -Double.MAX_VALUE
                    var minLon = Double.MAX_VALUE; var maxLon = -Double.MAX_VALUE
                    for ((lon, lat) in pts) {
                        if (lat < minLat) minLat = lat; if (lat > maxLat) maxLat = lat
                        if (lon < minLon) minLon = lon; if (lon > maxLon) maxLon = lon
                    }
                    val wkt = "LINESTRING(" + pts.joinToString(",") { "${it.first} ${it.second}" } + ")"
                    SpatialDbManager.insertRoute(route.name, wkt, minLat, maxLat, minLon, maxLon)
                    /* ROUTENOTESIMPORT-2026-09-08: AND ITS NARRATIVE.
                     *
                     * \u26d4 parseGpxRoutes has read <desc> into route.notes since
                     * 08-29 and NOTHING STORED IT, so every imported route
                     * arrived with an empty narrative -- proven on a real
                     * device-to-device transfer today.
                     *
                     * \u2b50 writeRouteNotes is the SAME function draft promotion
                     * uses. One writer; narrative and recipe cannot drift apart.
                     *
                     * \u26a0 THE ID IS RESOLVED BY HASH, not taken from insertRoute.
                     * That call is INSERT OR IGNORE and hands back the id it
                     * minted, which on a duplicate refers to no row at all.
                     * Resolving by hash also does the right thing on a
                     * re-import: the notes attach to the route that exists.
                     */
                    if (route.description.isNotBlank()) {
                        try {
                            val rgh = SpatialDbManager.computeGeomHash(wkt)
                            val rid = SpatialDbManager.findRouteIdByHash(rgh)
                            if (rid != null) {
                                /* ROUTENOTESSHAPE-2026-09-08: WHICH IS IT?
                                 *
                                 * \u26d4 parseGpxRoutes returns EITHER our
                                 * <grouptrack:notes> payload OR another app's
                                 * plain <desc>, in the same field -- it prefers
                                 * ours where present. Wrapping unconditionally
                                 * put the entire JSON document into the
                                 * headline, which is the gibberish Fred saw the
                                 * moment the export side started working.
                                 *
                                 * \u2b50 A real parse, not a startsWith("{"): prose
                                 * that happens to begin with a brace would be
                                 * accepted and stored as a notes object with no
                                 * narrative in it -- an empty panel rather than
                                 * an error, which is harder to notice.
                                 */
                                val payload = try {
                                    org.json.JSONObject(route.description)
                                } catch (_: Exception) {
                                    org.json.JSONObject().put(
                                        "narrative",
                                        org.json.JSONObject().put("headline", route.description)
                                    )
                                }
                                SpatialDbManager.writeRouteNotes(rid, payload)
                                android.util.Log.i("ConvoyTrackOps", "route '${route.name}': narrative stored")
                            } else {
                                android.util.Log.w("ConvoyTrackOps", "route '${route.name}': no row for hash, narrative dropped")
                            }
                        } catch (e: Exception) {
                            // \u26a0 A narrative that fails to store must not fail the
                            // import. The route itself is already in.
                            android.util.Log.w("ConvoyTrackOps", "route '${route.name}': narrative: ${e.message}")
                        }
                    }
                    // ROUTEMAPS-2026-09-24 (Fred): routes get their corridor maps too -- the SAME call the track
                    // path above and the route detail panel use. The importer only knew tracks because route
                    // corridors came later (ROUTECORR-2026-08-10C). Opt-in, exactly as for tracks.
                    if (downloadMapSlots.isNotEmpty()) {
                        try {
                            val gh = SpatialDbManager.computeGeomHash(wkt)
                            var queued = 0
                            for (slot in downloadMapSlots) {
                                queued += certEnqueueCorridor(context, gh, slot, replaceExisting)
                            }
                            onProgress?.invoke(
                                if (queued > 0) "MAPS: route ${route.name} corridor queued " +
                                    "(${downloadMapSlots.size} sources, $queued tiles)"
                                else "MAPS: route ${route.name} no corridor")
                            android.util.Log.i("ConvoyTrackOps", "ROUTEMAPS-2026-09-24: route '${route.name}' queued $queued tiles")
                        } catch (e: Exception) {
                            // A map failure must not fail the import -- the route is already in.
                            android.util.Log.w("ConvoyTrackOps", "route '${route.name}': maps: ${e.message}")
                        }
                    }
                    routeCount++
                } catch (e: Exception) {
                    errors.add("Route ${route.name}: ${e.message}")
                }
            }

            // ── 4. Delete source file after successful import ──
            val totalImported = trackFiles.size + waypointCount + routeCount
            if (totalImported > 0) {
                try {
                    sourceFile.delete()
                    android.util.Log.i("Import", "Deleted source file: $sourceName")
                } catch (e: Exception) {
                    android.util.Log.w("Import", "Could not delete source: ${e.message}")
                }
            }

            android.util.Log.i("Import", "Import complete: ${trackFiles.size} tracks, $waypointCount waypoints, $routeCount routes from $sourceName")
            if (trailsAdded > 0) certTrailsChanged()   // IMPORTTRAILS-2026-10-30: maps reload
            ImportArtifactsSummary(sourceName, trackFiles.size, waypointCount, routeCount, trackFiles, errors, insertedCount, duplicateCount, aliasedCount, skippedCount)

        } catch (e: Exception) {
            android.util.Log.e("Import", "Import failed for $sourceName: ${e.message}")
            ImportArtifactsSummary(sourceName, 0, 0, 0, emptyList(), listOf(e.message ?: "Unknown error"))
        }
    }
}
